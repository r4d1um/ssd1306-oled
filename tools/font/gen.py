"""Turn tools/font/font5x7.txt into src/ssd1306_font5x7.c (column bytes, bit 0 = top row)."""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tools/font/font5x7.txt"
OUT = ROOT / "src/ssd1306_font5x7.c"


def parse(text):
    glyphs, cp, rows = {}, None, []

    def done():
        if cp is None:
            return
        if len(rows) not in (7, 8) or any(len(r) != 5 or set(r) - set(".#") for r in rows):
            sys.exit(f"U+{cp:04X}: need 7 or 8 rows of 5 '.'/'#'")
        if cp in glyphs:
            sys.exit(f"U+{cp:04X}: defined twice")
        glyphs[cp] = rows + ["....."] * (8 - len(rows))

    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        if line.startswith("U+"):
            done()
            cp, rows = int(line[2:], 16), []
        else:
            rows.append(line)
    done()
    return glyphs


def columns(rows):
    return [sum(1 << y for y in range(8) if rows[y][x] == "#") for x in range(5)]


def main():
    g = parse(SRC.read_text(encoding="utf-8"))
    missing = [c for c in range(0x20, 0x7F) if c not in g]
    if missing:
        sys.exit("missing ASCII: " + " ".join(f"U+{c:04X}" for c in missing))
    extra = sorted(c for c in g if not 0x20 <= c <= 0x7E)
    out = ["/* SPDX-License-Identifier: MIT */",
           "/* Generated by tools/font/gen.py from tools/font/font5x7.txt - do not edit. */",
           '#include "ssd1306_font.h"', "",
           "/* ASCII 0x20..0x7E, 5 column bytes each, bit 0 = top row */",
           "const uint8_t ssd1306_font5x7_ascii[95][5] SSD1306_ROM = {"]
    for c in range(0x20, 0x7F):
        b = ", ".join(f"0x{v:02X}" for v in columns(g[c]))
        ch = chr(c) if chr(c) not in "\\*/" else " "
        out.append(f"    {{ {b} }}, /* {ch} */")
    out += ["};", "", "/* further code points, sorted for binary search */",
            f"const uint16_t ssd1306_font5x7_extra_cp[{len(extra)}] SSD1306_ROM = {{"]
    out += ["    " + ", ".join(f"0x{c:04X}" for c in extra[i:i + 8]) + "," for i in range(0, len(extra), 8)]
    out += ["};", f"const uint8_t ssd1306_font5x7_extra[{len(extra)}][5] SSD1306_ROM = {{"]
    for c in extra:
        b = ", ".join(f"0x{v:02X}" for v in columns(g[c]))
        out.append(f"    {{ {b} }}, /* U+{c:04X} */")
    out += ["};", f"const uint8_t ssd1306_font5x7_extra_count = {len(extra)};", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: 95 ASCII + {len(extra)} extra glyphs")


if __name__ == "__main__":
    main()
